async function line(page, x1, y1, x2, y2) {
  const canvas = page.locator("#noteCanvas");
  await canvas.scrollIntoViewIfNeeded();
  const rect = await canvas.boundingBox();
  await page.mouse.move(rect.x + rect.width * x1, rect.y + rect.height * y1);
  await page.mouse.down();
  await page.mouse.move(rect.x + rect.width * x2, rect.y + rect.height * y2, { steps: 20 });
  await page.mouse.up();
}
