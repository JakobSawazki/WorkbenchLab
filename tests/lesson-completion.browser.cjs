const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const { chromium } = require("playwright");
const base = process.env.WORKBENCH_TEST_URL || "http://127.0.0.1:4174/";
(async () => {
  const output = require("./artifacts.cjs")("completion-qa");
  fs.mkdirSync(output, { recursive: true });
  const browser = await chromium.launch({ headless: true, channel: "msedge" });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    await page.addInitScript(() => {
      if (!localStorage.getItem("workbenchlab-v1")) localStorage.setItem("workbenchlab-v1", JSON.stringify({ name: "TST.QAA", className: "TEST" }));
    });
    const errors = [];
    page.on("pageerror", (error) => errors.push(error.message));
    const state = () => page.evaluate(() => JSON.parse(localStorage.getItem("workbenchlab-v1")));
    await page.goto(`${base}?screenshot=1#lesson/relation-und-schluessel`);
    await page.locator(".lesson-head").waitFor();
    assert.ok(page.url().endsWith("#lesson/relation-und-schluessel"));
    assert.deepEqual((await state()).completedLessons, []);
    await page.goto(`${base}?screenshot=1#lesson/warum-datenbanken`);
    const ordered = await page.evaluate(() => window.WORKBENCH_CONTENT.modules.flatMap((module) => module.lessonIds).map((id) => window.WORKBENCH_CONTENT.lessons.find((item) => item.id === id)));
    const indicator = page.locator("#lessonModuleProgress");
    const bar = indicator.locator("progress");
    const menuCheck = id => page.locator(`#pathQuickMenu [data-lesson="${id}"] .path-lesson-check svg`);
    const first = ordered[0];
    const previousArrow = page.locator("#previousLessonButton");
    const nextArrow = page.locator("#nextLessonButton");
    const waitForLesson = lesson => page.waitForFunction(code => document.querySelector("#viewEyebrow [aria-current='page']")?.textContent === code, lesson.courseCode);
    const navigateTo = async (lesson, action) => {
      if (action) await action();
      else await page.goto(`${base}?screenshot=1#lesson/${lesson.id}`);
      await waitForLesson(lesson);
    };
    assert.ok(await previousArrow.isDisabled());
    assert.match(await nextArrow.getAttribute("aria-label"), /^Nächste Lerneinheit: L1\.2/);
    await navigateTo(ordered[1], () => nextArrow.press("Enter"));
    await navigateTo(first, () => previousArrow.click());
    const nextModule = ordered.findIndex(lesson => lesson.module !== first.module);
    await navigateTo(ordered[nextModule - 1]);
    await navigateTo(ordered[nextModule], () => nextArrow.click());
    assert.equal(await page.locator("#viewEyebrow .breadcrumb-link").innerText(), "L2");
    assert.equal(await bar.getAttribute("aria-label"), "Lernfortschritt L2");
    await navigateTo(ordered[nextModule - 1], () => previousArrow.click());
    await navigateTo(ordered.at(-1));
    assert.ok(await nextArrow.isDisabled());
    assert.deepEqual((await state()).completedLessons, []);
    await page.goto(`${base}?screenshot=1#home`);
    await indicator.waitFor({ state: "hidden" });
    await navigateTo(first);
    await page.setViewportSize({ width: 1100, height: 900 });
    await page.locator(".app-shell").evaluate(el => el.style.setProperty("--sidebar-width", "520px"));
    assert.ok(await page.evaluate(() => {
      const arrows = document.querySelector(".lesson-step-navigation").getBoundingClientRect();
      const progress = document.querySelector("#lessonModuleProgress").getBoundingClientRect();
      const topbar = document.querySelector(".topbar");
      return arrows.right <= progress.right + 1 && topbar.scrollWidth <= topbar.clientWidth + 1;
    }), "Lektionspfeile passen auch bei maximal breiter Seitenleiste");
    await page.locator(".app-shell").evaluate(el => el.style.removeProperty("--sidebar-width"));
    await page.setViewportSize({ width: 1440, height: 1000 });
    assert.equal(await indicator.locator("span").innerText(), "0 %");
    assert.equal(await menuCheck(first.id).count(), 0);
    assert.equal(await page.locator("[data-next-lesson]").count(), 0);
    await page.locator("[data-complete-lesson]").click();
    assert.equal(await page.locator('[data-lesson-check="0"]').evaluate((el) => document.activeElement === el), true);
    assert.deepEqual((await state()).completedLessons, []);
    for (const check of await page.locator("[data-lesson-check]").all()) await check.check();
    await page.reload();
    assert.equal(await page.locator("[data-lesson-check]:checked").count(), first.completionChecks.length);
    await page.locator("[data-complete-lesson]").click();
    assert.equal(await page.locator('#quizForm input[name="quizAnswer"]').first().evaluate((el) => document.activeElement === el), true);
    await page.locator('#quizForm button[type="submit"]').click();
    assert.equal(await page.locator('#quizForm input[name="quizAnswer"]').first().evaluate((el) => document.activeElement === el), true);
    assert.equal(await page.locator("#quizResult").getAttribute("role"), "status");
    assert.equal(await page.locator('#quizForm [role="radiogroup"]').getAttribute("aria-labelledby"), "quizQuestion");
    await page.locator(`input[name="quizAnswer"][value="${(first.quiz.correct + 1) % first.quiz.options.length}"]`).check();
    await page.locator('#quizForm button[type="submit"]').click();
    assert.ok(await page.locator("#quizResult.is-error").isVisible());
    assert.deepEqual((await state()).passedLessonQuizzes, []);
    await page.locator(`input[name="quizAnswer"][value="${first.quiz.correct}"]`).check();
    await page.locator('#quizForm button[type="submit"]').click();
    await page.locator("[data-complete-lesson]").click();
    assert.equal(await page.locator("[data-lesson-teacher]").evaluate((el) => document.activeElement === el), true);
    assert.deepEqual((await state()).completedLessons, []);
    for (let index = 0; index < ordered.length; index++) {
      const lesson = ordered[index];
      await waitForLesson(lesson);
      await page.locator("[data-lesson-reading]").waitFor();
      assert.ok(page.url().endsWith(`#lesson/${lesson.id}`));
      const inModule = ordered.filter(item => item.module === lesson.module);
      const done = inModule.filter(item => ordered.indexOf(item) <= index).length;
      assert.equal(await bar.evaluate(element => element.value), Math.round(100 * (done - 1) / inModule.length));
      await page.locator(`input[name="quizAnswer"][value="${lesson.quiz.correct}"]`).check();
      await page.locator('#quizForm button[type="submit"]').click();
      for (const check of await page.locator("[data-lesson-check], [data-lesson-teacher]").all()) await check.check();
      await page.locator("[data-complete-lesson]").click();
      assert.ok(await page.locator("[data-complete-lesson]").isDisabled());
      const percent = Math.round(100 * done / inModule.length);
      assert.equal(await bar.evaluate(element => element.value), percent);
      assert.equal(await indicator.locator("span").innerText(), `${percent} %`);
      assert.equal(await bar.getAttribute("aria-valuetext"), `${done} von ${inModule.length} Einheiten abgeschlossen (${percent} %)`);
      assert.equal(await menuCheck(lesson.id).count(), 1);
      assert.equal((await state()).completedLessons.length, index + 1);
      const entries = (await state()).nagoldEntries;
      assert.equal(entries.length, index + 1);
      const awarded = entries.filter(entry => entry.lessonId === lesson.id);
      assert.equal(awarded.length, 1);
      assert.equal(awarded[0].points, 5);
      assert.match(awarded[0].date, /^\d{4}-\d{2}-\d{2}$/);
      assert.match(awarded[0].time, /^(?:[01]\d|2[0-3]):[0-5]\d$/);
      if (index + 1 < ordered.length) {
        const next = page.locator("[data-next-lesson]");
        assert.equal(await next.getAttribute("data-lesson"), ordered[index + 1].id);
        assert.equal(await next.evaluate((el) => document.activeElement === el), true);
        if (index === 0) {
          await page.waitForFunction(() => !document.querySelector("#toastRegion").children.length);
          await page.locator('#sidebar [data-route="path"]').focus();
          const moduleButton = page.locator(`#pathQuickMenu [data-path-module="${lesson.module}"]`);
          await moduleButton.waitFor();
          await moduleButton.focus();
          await menuCheck(first.id).waitFor();
          assert.equal(await menuCheck(ordered[1].id).count(), 0);
          await page.locator(`#pathQuickMenu [data-lesson="${first.id}"]`).getByText("Abgeschlossen", { exact: true }).waitFor({ state: "attached" });
          await page.locator(".path-lesson-submenu").first().screenshot({ path: path.join(output, "completed-menu.png"), animations: "disabled" });
          await next.focus();
          await page.locator(".topbar").screenshot({ path: path.join(output, "progress-desktop.png"), animations: "disabled" });
          await page.screenshot({ path: path.join(output, "next-desktop.png"), animations: "disabled" });
          await page.setViewportSize({ width: 390, height: 844 });
          await page.locator("#appearanceButton").click();
          await page.locator('[data-font-size="20"]').click();
          await page.locator("#appearanceDoneButton").click();
          await next.scrollIntoViewIfNeeded();
          assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
          const mobileBar = await bar.boundingBox();
          for (const arrow of [previousArrow, nextArrow]) {
            const bounds = await arrow.boundingBox();
            assert.ok(bounds.width >= 24 && bounds.height >= 24 && bounds.x >= 0 && bounds.x + bounds.width <= 390);
            const iconSize = await arrow.locator("svg").evaluate(el => el.getBoundingClientRect().height);
            const labelSize = await indicator.locator("span").evaluate(el => parseFloat(getComputedStyle(el).fontSize));
            assert.ok(Math.abs(iconSize - labelSize) < 1);
          }
          assert.ok(mobileBar.width > 25 && mobileBar.x >= 0 && mobileBar.x + mobileBar.width <= 390);
          await page.locator(".topbar").screenshot({ path: path.join(output, "progress-mobile.png"), animations: "disabled" });
          await page.screenshot({ path: path.join(output, "next-mobile.png"), animations: "disabled" });
          await page.setViewportSize({ width: 1440, height: 1000 });
        }
        await next.click();
        await page.waitForURL(new RegExp(`#lesson/${ordered[index + 1].id}$`));
      } else assert.equal(await page.locator("[data-next-lesson]").count(), 0);
    }
    const xp = await page.locator("#topXp").innerText();
    assert.equal(Number(xp.replace(/\D/g, "")), ordered.reduce((sum, lesson) => sum + lesson.xp, 0));
    await page.goto(`${base}?screenshot=1#lesson/warum-datenbanken`);
    assert.ok(await page.locator("[data-complete-lesson]").isDisabled());
    assert.equal(await page.locator("#topXp").innerText(), xp);
    assert.equal((await state()).completedLessons.length, ordered.length);
    assert.equal(await bar.evaluate(element => element.value), 100);
    await page.goto(base + "#home");
    await indicator.waitFor({ state: "hidden" });
    assert.deepEqual(errors, []);
    console.log(`PASS: incomplete gates and focus, wrong/correct quiz, persistence, all ${ordered.length} sequential completions and module transitions, next-unit focus, final unit, no duplicate XP, mobile large font.`);
  } finally { await browser.close(); }
})().catch((error) => { console.error(error); process.exitCode = 1; });
